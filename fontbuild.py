"""Builds Tacit's symbols into two fonts the shell can load in place of Material Symbols:

    build/fonts/TacitSymbols.ttf        the line forms
    build/fonts/TacitSymbolsFill.ttf    the filled forms (a symbol without one keeps its line)
    build/fonts/tacit_symbols.js        the names the fonts answer to, for MaterialSymbol.qml's fallback

Like Material Symbols, a symbol is typed by name: a required ligature turns the letters of "wifi" into the glyph.
The fonts answer to Tacit's own names and to the Material names listed in aliases.py. Metrics are Material
Symbols' (960 units, the 24 grid at 40 units, ascent 1056, descent -96), so a symbol sits where Material's sat.

    fontbuild.py            (run with the font project's venv)
"""
import json
import os
import string

from fontTools.feaLib.builder import addOpenTypeFeaturesFromString
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.areaPen import AreaPen
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.ttGlyphPen import TTGlyphPen

import symbols as SY
from aliases import MATERIAL

UPM, K = 960, 40
DIGITS = dict(zip("0123456789", ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]))
CHARS = {**{c: c for c in string.ascii_lowercase}, **DIGITS, "_": "underscore", "-": "hyphen"}


def glyph(shape):
    rec = RecordingPen()
    shape.transform(K, 0, 0, -K, 0, UPM).draw(rec)
    area = AreaPen(None)
    rec.replay(area)
    pen = TTGlyphPen(None)
    rec.replay(Cu2QuPen(pen, max_err=0.6, reverse_direction=area.value > 0))      # TrueType: outer contours run clockwise
    return pen.glyph()


def empty():
    return TTGlyphPen(None).glyph()


def build(family, shapes, names, path):
    """shapes: Tacit name -> Path; names: typed name -> Tacit name."""
    gname = lambda n: "t." + n.replace("-", "_")
    order = [".notdef", "space"] + list(CHARS.values()) + [gname(n) for n in shapes]
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({32: "space", **{ord(c): g for c, g in CHARS.items()}})
    fb.setupGlyf({**{g: empty() for g in order}, **{gname(n): glyph(s) for n, s in shapes.items()}})
    # The left side bearing must be the outline's own left edge: FreeType moves a TrueType outline so that its
    # edge sits at the bearing, and a bearing of 0 pulled every symbol flush left in its box.
    glyf = fb.font["glyf"]
    metrics = {}
    for g in order:
        glyf[g].recalcBounds(glyf)
        metrics[g] = (UPM if g.startswith("t.") else 0, glyf[g].xMin if glyf[g].numberOfContours else 0)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=1056, descent=-96)
    fb.setupNameTable({"familyName": family, "styleName": "Regular", "copyright": "Copyright 2026 The Tacit Project", "version": "Version 0.1"})
    fb.setupOS2(sTypoAscender=1056, sTypoDescender=-96, sTypoLineGap=0, usWinAscent=1062, usWinDescent=91, achVendID="TCIT")
    fb.setupPost()
    rules = sorted(names.items(), key=lambda kv: (-len(kv[0]), kv[0]))
    fea = "languagesystem DFLT dflt;\nlanguagesystem latn dflt;\nfeature rlig {\n" + \
          "".join(f"    sub {' '.join(CHARS[c] for c in typed)} by {gname(to)};\n" for typed, to in rules) + "} rlig;\n"
    addOpenTypeFeaturesFromString(fb.font, fea)
    fb.save(path)


if __name__ == "__main__":
    line = {n: (s[0] if isinstance(s, tuple) else s) for n, s in SY.symbols().items()}       # a dimmed part is left out: one colour per glyph
    fill = {**line, **{n: s for n, s in SY.filled().items() if s is not None}}
    names = {n: n for n in line if all(c in CHARS for c in n)}
    names.update({m: t for m, t in MATERIAL.items() if t in line})
    missing = sorted(t for t in set(MATERIAL.values()) if t not in line)
    os.makedirs("build/fonts", exist_ok=True)
    build("Tacit Symbols", line, names, "build/fonts/TacitSymbols.ttf")
    build("Tacit Symbols Fill", fill, names, "build/fonts/TacitSymbolsFill.ttf")
    open("build/fonts/tacit_symbols.js", "w").write(".pragma library\n// Generated by fontbuild.py: the names Tacit Symbols answers to.\nvar names = " + json.dumps({n: 1 for n in sorted(names)}) + ";\n")
    inv = json.load(open("inventory.json")) if os.path.exists("inventory.json") else {}
    covered = [n for n in inv if n in names]
    uses = sum(v["count"] for v in inv.values()); cov_uses = sum(inv[n]["count"] for n in covered)
    print(len(line), "symbols,", len(fill) - len(line) + len([n for n in SY.filled() if SY.filled]) and len(SY.filled()), "filled forms,", len(names), "names")
    print(f"shell coverage: {len(covered)} of {len(inv)} names, {cov_uses} of {uses} uses ({100 * cov_uses // max(uses, 1)} %)")
    if missing:
        print("aliases pointing at symbols not drawn:", " ".join(missing))
